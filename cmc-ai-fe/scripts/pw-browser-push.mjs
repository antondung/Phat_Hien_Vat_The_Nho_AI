/** E2E: thêm camera "gửi hình qua trình duyệt" (Chrome camera giả) → BE nhận khung → tải lại trang vẫn tự gửi tiếp. */
import { createRequire } from 'node:module';
const { chromium } = createRequire(import.meta.url)('/workspace/pwtest/node_modules/playwright-core');
const BASE = process.env.FE_URL || 'http://127.0.0.1:5179';
const BE = process.env.BE_URL || 'http://127.0.0.1:8030';
const OUT = '/workspace/fe-shots/browser-push';
const b = await chromium.launch({ executablePath: '/usr/bin/google-chrome', args: ['--no-sandbox', '--use-fake-ui-for-media-stream', '--use-fake-device-for-media-stream'] });
const ctx = await b.newContext({ viewport: { width: 1229, height: 603 } });
const p = await ctx.newPage();
p.on('pageerror', (e) => console.log('PAGEERR', e.message));
let wsSent = 0, httpPush = 0;
p.on('websocket', (ws) => { if (ws.url().includes('/push')) { console.log('WS', ws.url().slice(0, 80)); ws.on('framesent', () => wsSent++); ws.on('close', () => console.log('WS closed')); } });
p.on('request', (r) => { if (r.url().includes('/frame')) httpPush++; });
await p.goto(`${BASE}/dang-nhap`);
await p.fill('input[type="email"]', 'admin@cmc.edu.vn'); await p.fill('input[type="password"]', 'admin123');
await p.click('button.btn-primary'); await p.waitForSelector('.sidebar');
const tok = await p.evaluate(() => Object.entries(localStorage).find(([k, v]) => /token|auth/i.test(k))?.[1]);
await p.goto(`${BASE}/cai-dat/camera`);
await p.getByRole('button', { name: /Thêm camera điện thoại/ }).click();
await p.waitForSelector('.phone-browser-push');
await p.getByRole('button', { name: /Tìm camera trên trình duyệt/ }).click();
await p.waitForSelector('.phone-browser-row select');
await p.locator('.phone-browser-push').scrollIntoViewIfNeeded();
await p.screenshot({ path: OUT + '/1-chon-camera.png' });
const opts = await p.locator('.phone-browser-row option').allTextContents();
console.log('browser cams', opts);
await p.getByRole('button', { name: /Lưu và gửi hình qua trình duyệt/ }).click();
await p.waitForTimeout(4000);
const ls = await p.evaluate(() => localStorage.getItem('cmcai.localPush.v1'));
const camId = JSON.parse(ls)[0].cameraId;
console.log('camera', camId);
const authTok = (() => { try { const v = JSON.parse(tok); return v.token || v.accessToken || v; } catch { return tok; } })();
const diag = async () => (await (await fetch(`${BE}/api/cameras/${camId}/diag`, { headers: { Authorization: `Bearer ${authTok}` } })).json());
const d1 = await diag(); console.log('diag1', JSON.stringify(d1).slice(0, 400), 'wsSent', wsSent, 'http', httpPush);
const st = await (await fetch(`${BE}/api/cameras/status`, { headers: { Authorization: `Bearer ${authTok}` } })).json();
console.log('status', JSON.stringify(st.find((x) => x.cameraId === camId)));
await p.goto(`${BASE}/giam-sat/camera/${camId}`); await p.waitForTimeout(5000);
await p.screenshot({ path: OUT + '/2-camera-don.png' });
await p.reload(); await p.waitForTimeout(6000);
const d2 = await diag(); console.log('wsSent', wsSent, 'http', httpPush); console.log('diag2-after-reload', JSON.stringify(d2).slice(0, 400));
await p.screenshot({ path: OUT + '/3-sau-tai-lai.png' });
await b.close();
